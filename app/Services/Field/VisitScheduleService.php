<?php

declare(strict_types=1);

namespace App\Services\Field;

use App\Models\WebAccount;
use App\Services\AccountAccess;
use App\Services\AccountAuditTrail;
use App\Services\Finance\Fields;
use App\Services\ProjectNumberAllocator;
use App\Services\Staff\NoticeService;
use Carbon\CarbonImmutable;
use Illuminate\Database\Query\Builder;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\DB;
use Illuminate\Validation\ValidationException;

/**
 * The visit schedule (M4.12, desktop `Visits_Schedule_Form`) on the unified schema: the shared visit and clearance notices (`web_notices`,
 * `account_id` NULL) of the permitted cities with the project's current state, donor, type, areas, mobile and next unpaid instalment, and
 * whether the visit was done (a matching `visits` / `me_visits` row, Kobo ones included). Actions with `visits.manage` in the notice's city:
 * hide / restore, note, and the web's rescheduling (new date and reason, the original date kept, optionally moving the project's later
 * unseen visits). Reading needs `applications.view` + `visits.view`; the export also `reports.export`. Notices are generated by
 * `ProjectNotices::generateVisitSchedule` (M4.9); notices have no soft delete, so "delete" stays `seen = 1` as on the desktop.
 */
final class VisitScheduleService
{
    public const PER_PAGE = 50;

    /** The desktop's visit filter: Opening, M1–M5, MFinal, Closing, Clearance. */
    public const VISITS = ['Opening', 'M1', 'M2', 'M3', 'M4', 'M5', 'MFinal', 'Closing', 'Clearance'];

    public function __construct(private AccountAccess $access, private AccountAuditTrail $audit, private NoticeService $notices) {}

    /** Cities where the account may read visits. */
    public function cities(WebAccount $account): Collection
    {
        return $this->access->citiesWithAll($account, ['applications.view', 'visits.view']);
    }

    private function permitted(WebAccount $account, bool $export): Collection
    {
        $permitted = $this->cities($account);
        if ($export) {
            $permitted = $permitted->filter(fn ($city) => $this->access->check($account, (int) $city->id, 'reports.export'))->values();
        }
        if ($permitted->isEmpty()) {
            $this->audit->record($account->id, 'access.denied', 'denied');
            abort(403);
        }

        return $permitted;
    }

    /** The page was opened: refused without visits in any city, else audited once. */
    public function opened(WebAccount $account): void
    {
        $this->permitted($account, false);
        $this->audit->record($account->id, 'visits.schedule', 'succeeded');
    }

    /**
     * @param  array{cities?: list<int>, year?: ?int, months?: list<int>, kind?: ?string, visit?: ?string, street?: ?int, type?: ?int, hidden?: bool, q?: ?string}  $filters
     */
    public function schedule(WebAccount $account, array $filters): array
    {
        $permitted = $this->permitted($account, false);
        $query = $this->query($permitted, $filters);
        $rows = $query->orderBy('n.notice_date')->orderBy('n.id')->paginate(self::PER_PAGE);
        $rows->setCollection($this->decorate($rows->getCollection()));
        $ids = $this->ids($permitted, $filters);

        return [
            'rows' => $rows, 'cityOptions' => $permitted,
            'manageCities' => $permitted->filter(fn ($city) => $this->access->check($account, (int) $city->id, 'visits.manage'))->pluck('id')->map(fn ($id) => (int) $id)->all(),
            'canExport' => $permitted->contains(fn ($city) => $this->access->check($account, (int) $city->id, 'reports.export')),
            'streets' => DB::table('streets')->whereIn('city_id', $ids)->orderBy('name_ar')->get(['id', 'city_id', 'name_ar', 'name_en']),
            'types' => DB::table('project_types')->orderBy('sort_order')->orderBy('id')->get(['id', 'name_ar', 'name_en']),
        ];
    }

    private function ids(Collection $permitted, array $filters): array
    {
        $selected = array_values(array_intersect(array_map('intval', $filters['cities'] ?? []), $permitted->pluck('id')->map(fn ($id) => (int) $id)->all()));

        return $selected !== [] ? $selected : $permitted->pluck('id')->map(fn ($id) => (int) $id)->all();
    }

    private function query(Collection $permitted, array $filters): Builder
    {
        $current = DB::table('project_state_history as h')->join('project_states as s', 's.id', '=', 'h.project_state_id')->where('h.is_current', true)->whereNull('h.deleted_at')
            ->select(['h.project_id', 's.name_ar as state_ar', 's.name_en as state_en']);
        $query = DB::table('web_notices as n')->join('cities as c', 'c.id', '=', 'n.city_id')->leftJoin('projects as p', 'p.id', '=', 'n.project_id')
            ->leftJoinSub($current, 'st', 'st.project_id', '=', 'n.project_id')
            ->leftJoin('donors as d', 'd.id', '=', 'p.donor_id')->leftJoin('project_types as t', 't.id', '=', 'p.project_type_id')->leftJoin('streets as ps', 'ps.id', '=', 'p.street_id')
            ->whereIn('n.city_id', $this->ids($permitted, $filters))->whereIn('n.kind', NoticeService::SHARED)->whereNull('n.account_id')
            ->select(['n.id', 'n.city_id', 'n.project_id', 'n.project_number', 'n.kind', 'n.notice_date', 'n.original_date', 'n.change_reason', 'n.title', 'n.body', 'n.note', 'n.seen',
                'c.code as city_code', 'c.name_ar as city_ar', 'c.name_en as city_en', 'p.name as project_name', 'p.project_number as number',
                'st.state_ar', 'st.state_en', 'd.name_ar as donor_ar', 'd.name_en as donor_en', 't.name_ar as type_ar', 't.name_en as type_en', 'ps.name_ar as project_area']);
        if (empty($filters['hidden'])) {
            $query->where('n.seen', false);
        }
        if (! empty($filters['year'])) {
            $query->whereBetween('n.notice_date', [sprintf('%04d-01-01', $filters['year']), sprintf('%04d-12-31', $filters['year'])]);
        }
        if (! empty($filters['months'])) {
            $months = array_values(array_map('intval', $filters['months']));
            $expression = DB::connection()->getDriverName() === 'sqlite' ? "CAST(strftime('%m', n.notice_date) AS INTEGER)" : 'MONTH(n.notice_date)';
            $query->whereRaw($expression.' in ('.implode(',', array_fill(0, count($months), '?')).')', $months);
        }
        if (in_array($filters['kind'] ?? '', ['V', 'O'], true)) {
            $query->where('n.body', 'like', '%-'.$filters['kind'].'%');
        }
        $visit = $filters['visit'] ?? null;
        if (in_array($visit, self::VISITS, true)) {
            $visit === 'Clearance' ? $query->where('n.kind', NoticeService::CLEARANCE) : $query->where('n.body', 'like', 'Visit '.$visit.'-%');
        }
        if (! empty($filters['street'])) {
            $query->where('p.street_id', (int) $filters['street']);
        }
        if (! empty($filters['type'])) {
            $query->where('p.project_type_id', (int) $filters['type']);
        }
        $q = trim((string) ($filters['q'] ?? ''));
        if ($q !== '') {
            $query->where(function (Builder $w) use ($q) {
                $like = '%'.str_replace(['\\', '%', '_'], ['\\\\', '\\%', '\\_'], $q).'%';
                $w->where('n.title', 'like', $like)->orWhere('p.name', 'like', $like)->orWhere('n.body', 'like', $like)->orWhere('n.note', 'like', $like);
                if (ctype_digit($q)) {
                    $w->orWhere('n.project_number', (int) $q);
                }
            });
        }

        return $query;
    }

    /** Adds the beneficiary's home area and mobile, the next unpaid instalment and the visit status to a page of rows. */
    private function decorate(Collection $rows): Collection
    {
        $projects = $rows->pluck('project_id')->filter()->map(fn ($id) => (int) $id)->unique()->values()->all();
        $people = DB::table('project_applicants as a')->join('people as pe', 'pe.id', '=', 'a.person_id')->leftJoin('streets as s', 's.id', '=', 'pe.street_id')
            ->whereIn('a.project_id', $projects ?: [0])->whereNull('a.deleted_at')->orderByRaw("CASE WHEN a.role = 'مستفيد' THEN 0 ELSE 1 END")->orderBy('a.id')
            ->get(['a.project_id', 'a.person_id', 'pe.mobile', 's.name_ar as home_area', 'pe.first_name', 'pe.last_name', 'pe.father_name'])->groupBy('project_id');
        $next = DB::table('loan_installments as i')->join('loans as l', 'l.id', '=', 'i.loan_id')->whereIn('l.project_id', $projects ?: [0])->whereNull('l.deleted_at')->whereNull('i.deleted_at')
            ->where('i.is_paid', false)->groupBy('l.project_id')->select(['l.project_id', DB::raw('MIN(i.due_on) as due')])->pluck('due', 'project_id');
        $status = $this->status($rows, $people);

        return $rows->map(function ($row) use ($people, $next, $status) {
            $first = ($people[$row->project_id] ?? collect())->first();
            $row->display_number = ProjectNumberAllocator::display((string) $row->city_code, (int) ($row->number ?? $row->project_number));
            $row->home_area = $first->home_area ?? null;
            $row->mobile = $first->mobile ?? null;
            $row->next_due = Fields::day($next[$row->project_id] ?? null);
            $row->notice_date = Fields::day($row->notice_date);
            $row->original_date = Fields::day($row->original_date);
            $row->status = $status[(int) $row->id] ?? null;

            return $row;
        });
    }

    /**
     * The desktop's "visit status": done when the project has a visit of the notice's phase (opening / closing by kind) or, for M1–M5 and
     * MFinal (= number 4), an M&E visit of that number for the person the notice names (any person of the project when the name does not
     * match). Clearance notices have no visit ('na').
     *
     * @return array<int, ?string> notice id => 'done' | 'na' | null
     */
    private function status(Collection $rows, Collection $people): array
    {
        $projects = $rows->pluck('project_id')->filter()->map(fn ($id) => (int) $id)->unique()->values()->all();
        $kinds = DB::table('visits')->whereIn('project_id', $projects ?: [0])->whereNull('deleted_at')->get(['project_id', 'kind'])->groupBy('project_id');
        $me = DB::table('me_visits')->whereIn('project_id', $projects ?: [0])->whereNull('deleted_at')->get(['project_id', 'person_id', 'visit_number'])->groupBy('project_id');
        $out = [];
        foreach ($rows as $row) {
            $body = (string) $row->body;
            $project = (int) $row->project_id;
            if ($row->kind === NoticeService::CLEARANCE || preg_match('/\AVisit (Opening|Closing|M(\d)|MFinal)-/', $body, $m) !== 1) {
                $out[(int) $row->id] = 'na';

                continue;
            }
            if ($m[1] === 'Opening' || $m[1] === 'Closing') {
                $needle = $m[1] === 'Opening' ? 'op' : 'cl';
                $done = ($kinds[$project] ?? collect())->contains(fn ($v) => str_contains((string) $v->kind, $needle));
            } else {
                $number = $m[1] === 'MFinal' ? '4' : $m[2];
                $person = ($people[$project] ?? collect())->first(fn ($p) => trim(trim(($p->first_name ?? '').' '.($p->last_name ?? '')).' ابن/ة '.($p->father_name ?? '')) === $row->title);
                $done = ($me[$project] ?? collect())->contains(fn ($v) => (string) $v->visit_number === $number && ($person === null || (int) $v->person_id === (int) $person->person_id));
            }
            $out[(int) $row->id] = $done ? 'done' : null;
        }

        return $out;
    }

    /** Headings and rows of the Excel/CSV export (every row of the filters), audited before the first byte. */
    public function export(WebAccount $account, array $filters): array
    {
        $permitted = $this->permitted($account, true);
        $query = $this->query($permitted, $filters)->orderBy('n.notice_date')->orderBy('n.id');
        $this->audit->record($account->id, 'reports.exported', 'succeeded');
        $en = app()->getLocale() === 'en';

        return [array_map(fn ($k) => __('visits.schedule.columns.'.$k), ['number', 'project', 'beneficiary', 'state', 'donor', 'type', 'visit', 'date', 'home_area', 'project_area', 'mobile', 'next_due', 'status', 'note']),
            (function () use ($query, $en) {
                foreach ($query->lazy(500)->chunk(500) as $chunk) {
                    foreach ($this->decorate(collect($chunk->all())) as $r) {
                        yield [$r->display_number, $r->project_name, $r->title, $en && $r->state_en ? $r->state_en : $r->state_ar, $en && $r->donor_en ? $r->donor_en : $r->donor_ar,
                            $en && $r->type_en ? $r->type_en : $r->type_ar, $r->body, $r->notice_date, $r->home_area, $r->project_area, $r->mobile, $r->next_due,
                            match ($r->status) {
                                'done' => __('visits.schedule.done'), 'na' => '—', default => __('visits.schedule.not_yet')
                            }, $r->note];
                    }
                }
            })()];
    }

    // ---------------------------------------------------------------- actions

    /** The stored shared notice when the account may manage visits of its city. */
    private function manageable(WebAccount $account, int $noticeId): object
    {
        $notice = DB::table('web_notices')->where('id', $noticeId)->whereIn('kind', NoticeService::SHARED)->whereNull('account_id')->first();
        abort_if($notice === null || ! $this->cities($account)->contains('id', (int) $notice->city_id), 404);
        if (! $this->access->check($account, (int) $notice->city_id, 'visits.manage')) {
            $this->audit->record($account->id, 'access.denied', 'denied', (int) $notice->city_id);
            abort(403);
        }

        return $notice;
    }

    /** Hides (seen = 1) or restores (0) a shared notice, as the desktop's schedule delete / restore. */
    public function setSeen(WebAccount $account, int $noticeId, bool $hidden): void
    {
        $notice = $this->manageable($account, $noticeId);
        if ((bool) $notice->seen === $hidden) {
            return;
        }
        DB::transaction(function () use ($account, $notice, $hidden) {
            $this->notices->setSeenLike($notice, $hidden ? 1 : 0);
            $this->audit->record($account->id, 'notifications.seen', 'succeeded', (int) $notice->city_id,
                details: [['field' => 'notice', 'before' => $notice->body.' · '.Fields::day($notice->notice_date).' · '.($hidden ? 'ظاهر' : 'مخفي'), 'after' => $notice->body.' · '.($hidden ? 'مخفي' : 'ظاهر')]]);
        });
    }

    /** Replaces the note of a shared notice (`Update_Notification_Note`). */
    public function setNote(WebAccount $account, int $noticeId, string $note): void
    {
        $notice = $this->manageable($account, $noticeId);
        $note = trim($note);
        mb_strlen($note) <= 65535 || throw ValidationException::withMessages(['note' => __('visits.errors.long')]);
        $note = $note === '' ? null : $note;
        if ($note === $notice->note) {
            return;
        }
        DB::transaction(function () use ($account, $notice, $note) {
            DB::table('web_notices')->where('id', $notice->id)->update(['note' => $note]);
            $this->audit->record($account->id, 'notifications.noted', 'succeeded', (int) $notice->city_id,
                details: [['field' => 'note', 'before' => $notice->note, 'after' => $note]]);
        });
    }

    /**
     * Gives a not-yet-seen visit a new date and a reason, keeping its original date. With `$shiftLater` the project's later unseen visits move
     * by the same number of days. Returns how many notices changed.
     */
    public function reschedule(WebAccount $account, int $noticeId, string $date, string $reason, bool $shiftLater): int
    {
        $notice = $this->manageable($account, $noticeId);
        $fail = fn (string $field, string $key): never => throw ValidationException::withMessages([$field => __('visits.schedule.errors.'.$key)]);
        $notice->kind === NoticeService::VISIT || $fail('date', 'kind');
        (int) $notice->seen === 0 || $fail('date', 'seen');
        $date = trim($date);
        Fields::isDate($date) || $fail('date', 'date');
        $reason = trim($reason);
        ($reason !== '' && mb_strlen($reason) <= 65535) || $fail('reason', 'reason');
        $days = (int) CarbonImmutable::parse(Fields::day($notice->notice_date))->diffInDays(CarbonImmutable::parse($date), false);
        $days !== 0 || $fail('date', 'same');

        return DB::transaction(function () use ($account, $notice, $days, $reason, $shiftLater) {
            $targets = collect([$notice]);
            if ($shiftLater && $notice->project_id !== null) {
                $targets = $targets->concat(DB::table('web_notices')->where('city_id', $notice->city_id)->where('project_id', $notice->project_id)->where('kind', NoticeService::VISIT)
                    ->whereNull('account_id')->where('seen', false)->where('id', '<>', $notice->id)
                    ->where(fn ($q) => $q->where('notice_date', '>', $notice->notice_date)->orWhere(fn ($same) => $same->where('notice_date', $notice->notice_date)->where('id', '>', $notice->id)))
                    ->orderBy('notice_date')->orderBy('id')->get());
            }
            $details = [];
            foreach ($targets as $target) {
                $from = Fields::day($target->notice_date);
                $moved = CarbonImmutable::parse($from)->addDays($days)->toDateString();
                DB::table('web_notices')->where('id', $target->id)->update(['original_date' => $target->original_date ?? $from, 'notice_date' => $moved, 'change_reason' => $reason]);
                $details[] = ['field' => 'notice_date', 'before' => $target->body.' · '.$from, 'after' => $target->body.' · '.$moved];
            }
            $details[] = ['field' => 'change_reason', 'before' => $notice->change_reason, 'after' => $reason];
            $this->audit->record($account->id, 'notifications.rescheduled', 'succeeded', (int) $notice->city_id, details: $details);

            return $targets->count();
        });
    }
}
