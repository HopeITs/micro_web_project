<?php

/*
 * Generates one Eloquent model per table of the approved unified schema v1.1 (app/Models/<Class>.php):
 * base class by scope, casts by column type, belongsTo for every foreign key and hasMany for the
 * standard reverse links. Hand-written models (marked "@handwritten") are never overwritten.
 *
 * Usage: php tools/schema/generate-models.php
 */

require dirname(__DIR__, 2).'/vendor/autoload.php';

use Illuminate\Support\Str;

$root = dirname(__DIR__, 2);
$schema = json_decode(file_get_contents($root.'/docs/planning/m1/unified-schema-v1.1.json'), true);
if ($schema['sha256'] !== 'a783e7f335baac175f1fa3bd01905725200b54978c53a4a4b6f7f72b6e93047e') {
    fwrite(STDERR, "Not the approved v1.1 schema.\n");
    exit(1);
}

$class = fn (string $table) => Str::studly(Str::singular($table));
$base = ['city' => 'CityModel', 'lookup' => 'LookupModel', 'city_lookup' => 'CityLookupModel', 'global' => null, 'explicit' => null];
$standardCityColumns = ['id', 'city_id', 'legacy_id', 'created_at', 'updated_at', 'deleted_at'];

// Reverse links: table => [[childTable, column]]
$reverse = [];
foreach ($schema['tables'] as $table => $t) {
    foreach ($t['columns'] as $c) {
        if (isset($c['references']) && $c['name'] === Str::singular($c['references']).'_id' && $c['name'] !== 'city_id') {
            $reverse[$c['references']][] = [$table, $c['name']];
        }
    }
}

$written = 0;
$skipped = [];
foreach ($schema['tables'] as $table => $t) {
    $name = $class($table);
    $file = "{$root}/app/Models/{$name}.php";
    if (is_file($file) && str_contains(file_get_contents($file), '@handwritten')) {
        $skipped[] = $name;

        continue;
    }
    $cols = array_column($t['columns'], null, 'name');
    $casts = [];
    $methods = [];
    $uses = ['Illuminate\Database\Eloquent\Relations\BelongsTo' => false, 'Illuminate\Database\Eloquent\Relations\HasMany' => false];
    foreach ($t['columns'] as $c) {
        [$type, $arg] = array_pad(explode(':', $c['type'], 2), 2, null);
        $cast = match ($type) {
            'bool' => 'boolean',
            'date' => 'date',
            'datetime' => 'datetime',
            'dec' => 'decimal:'.explode(',', $arg)[1],
            'json' => 'array',
            'int', 'uint', 'smallint', 'tinyint', 'fk' => 'integer',
            default => null,
        };
        if ($cast && ! in_array($c['name'], ['id', 'created_at', 'updated_at', 'deleted_at'], true)) {
            $casts[$c['name']] = $cast;
        }
        if (isset($c['references']) && ! ($c['name'] === 'city_id' && in_array($t['scope'], ['city', 'city_lookup'], true))) {
            $method = Str::camel(preg_replace('/_id$/', '', $c['name']));
            $methods[] = "    public function {$method}(): BelongsTo\n    {\n        return \$this->belongsTo({$class($c['references'])}::class, '{$c['name']}');\n    }";
            $uses['Illuminate\Database\Eloquent\Relations\BelongsTo'] = true;
        }
    }
    foreach ($reverse[$table] ?? [] as [$child, $column]) {
        $method = Str::camel($child);
        $methods[] = "    public function {$method}(): HasMany\n    {\n        return \$this->hasMany({$class($child)}::class, '{$column}');\n    }";
        $uses['Illuminate\Database\Eloquent\Relations\HasMany'] = true;
    }

    $parent = $base[$t['scope']];
    $imports = $parent ? ["App\\Models\\Base\\{$parent}"] : ['Illuminate\Database\Eloquent\Model'];
    foreach ($uses as $u => $on) {
        if ($on) {
            $imports[] = $u;
        }
    }
    sort($imports);
    $extends = $parent ?? 'Model';
    $props = ["    protected \$table = '{$table}';"];
    if (! $parent) {
        $props[] = "    protected \$guarded = ['id'];";
    }
    if (! isset($cols['created_at'], $cols['updated_at'])) {
        $props[] = '    public $timestamps = false;';
    }
    $castLines = implode("\n", array_map(fn ($k, $v) => "            '{$k}' => '{$v}',", array_keys($casts), $casts));
    $doc = "/**\n * Table `{$table}` (".$t['scope'].(isset($t['source']) ? ', from desktop `'.$t['source'].'`' : '').").\n * Generated by tools/schema/generate-models.php from the approved unified schema v1.1; add behaviour in a\n * hand-written model only after marking it @handwritten.\n */";
    $body = implode("\n\n", array_filter([
        implode("\n\n", $props),
        $casts ? "    protected function casts(): array\n    {\n        return [\n{$castLines}\n        ];\n    }" : null,
        implode("\n\n", $methods) ?: null,
    ]));
    $code = "<?php\n\nnamespace App\\Models;\n\n".implode("\n", array_map(fn ($i) => "use {$i};", $imports))."\n\n{$doc}\nclass {$name} extends {$extends}\n{\n{$body}\n}\n";
    file_put_contents($file, $code);
    $written++;
}

echo "written {$written} models; kept hand-written: ".implode(', ', $skipped)."\n";
